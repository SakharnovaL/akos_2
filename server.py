import asyncio                                                                      #библиотека для асинхроного программирования, нужна для обслуживания 100500 миллиардов клиентов без зависания
import socket

dis_port = range(55555, 55565)                                                      #для одновременной работы сразу нескольких серверов 
chat_client = set()                                                                 #храним объекты write (клиентов), которые общаются друг с другом через сервер 
#функции для режима работы 1: общение клиента с сервером
async def conect_server_client(tcp_port):                                           #объявляем корутину и передаем свободный порт, которая выделила программа
    loop = asyncio.get_running_loop()                                               #получаем ссылку на Event Loop, который запущен в main. нам это надо, чтоб обычный сокет работал с await. так он не работает, потому что он нафиг все блокирует и ждет пока ему что-то придет
    upd_sok = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)                      #создаем неблокирующий upd сокет, чтоб клиент мог находить наш сервер
    upd_sok.setblocking(False)                                                      #делаем неблокирующим, иначе нахуй все заморозит и только он один будет ждать, пока ему что-то пришлют
    bound_port = None                                                               #флаг занятости портов для подключения, если дойдем до конца, а он все еще None, то все порты заняты. здесь именно None, чтоб обозначиьь пустоту, 0 вполне рабочий порт
    for port in dis_port:                                                           #перебираем порты
        try:
            upd_sok.bind(("0.0.0.0", port))                                         #пытаемся подключится к порту
            bound_port = port                                                       #выполнится только если успешно сработал bind 
            break
        except OSError:                                                             #сработает если bind не смог подключится к порту
            continue
    if bound_port is None:                                                          #если все порты заняты
        upd_sok.close()                                                             #закрываем udp порт, чтоб он невалялся просто так у нас и не ломал нам ничего
        raise RuntimeError('все порты (55555, 55565) заняты')
    try:
        while True:
            data, adr = await loop.sock_recvfrom(upd_sok, 1024)                     #ожидаем пока нам что-то отправит клиент, но при этом, пока к нам ничего не прилетело, стоим на паузе и не мешаем основной работе программы
            if data.decode('utf-8').strip() == 'who_server':
                mes = f'i_server:{tcp_port}'
                await loop.sock_sendto(upd_sok, mes.encode('utf-8'), adr)           #на адресс, с которого нам что-то пришло, отправляем реальный номер tcp порта
    finally:
        upd_sok.close()

async def handle_ping_mode(reader, writer, adr):                                    #объявляем корутину, которая работает для общения сервера с клиентом 
    print(f'клиент {adr} начал диалог с сервером')
    while True:
        try:
            data = await reader.read(1024)                                          #пока клиент не передает никакие сообщения, его корутина ставится на паузу (await), и сервер спокойно переключается на других клиентов, которые готовы с нами болтать
        except ConnectionError:                                                     #если клиент умер
            print(f"Client suddenly closed while receiving from {adr}")
            break
        if not data:                                                                #это разрыв соединения со стороны клиента, если он вызвал connection.close(), закрыл окно или просто получил строку b"". если убрать эту проверку, то мы будем получать дофига пустых строк и сервер уйдет в холостой бесконечный цикл и будет нам выводить дофига и больше пустых строк
            break
        income_message = data.decode('utf-8').strip()
        print(f"получено от {adr}: {income_message}")
        if income_message.lower() == 'ping':
            outgoing_message = 'pong'
        else:
            print('пришло сообщение не ping')
            outgoing_message = 'stupid man'
        try:
            writer.write(outgoing_message.encode('utf-8'))                                                      #мы складываем измененное полученное сообщение клиента в буфер отправки, но не отправляем 
            await writer.drain()                                                    #для больших сообщений или файлов будет нагляднее, но и для нашего случая это надо, чтоб у нас сначала отправлялось сообщение, а уже потом переходили к чтению нового. и плюсом с этой штукой у нас не будут все клиенты тормозить из-за одного идиота с отвратительным инетом, а только он будет тупить, а все остальные нормально работать. и здесь же, если вдруг что, падаем в ошибку отключения клиента
        except ConnectionError:                                                     #клиент умер, в момент отправки сообщения
            print(f"Client suddenly closed, cannot send")
            break

#функции для режима работы 2: общение клиента с клиентом (клиентами) через сервер
async def broadcast(message, sender_writer=None):                                   #корутина, которая отправляет полученное сообщение всем, кроме отправителя. None нужно, чтоб отправлять системные сообщения по типу "бро отключился"
    for client_writer in list(chat_client):                                         #оборачиваем множество в list, чтоб если случится отключение клиента у нас не выпала ошибка
        if client_writer is not sender_writer:
            try:                                                                    #пытаемся отправить сообщение, если вдруг клиент отключился ничего не поломается а протсо выполнится pass  
                client_writer.write(message.encode('utf-8'))
                await client_writer.drain()                                         #ждем пока сообщение реально отправится
            except ConnectionError:
                pass

async def handle_chat_mode(reader, writer, adr):                                    #корутина, которая читает и оправляет сообщения в общий чат для каждого отдельного клиента
    print(f'клиент {adr} подключился к общему чату клиентов')
    chat_client.add(writer)                                                         #добавляем именно writer, потому что он умеет оправлять сообщения, если не будем его добавлять, то общаться не сможем
    await broadcast(f'к чату присоединился {adr}', sender_writer=writer)            #пишем в чате, что клиент подключился. sender_writer=writer нужно, чтоб тебе самому не пришло сообщение, что ты подключился
    try:
        while True:
            try:
                data = await reader.read(1024)                                      #пока клиент не передает никакие сообщения, его корутина ставится на паузу (await), и сервер спокойно переключается на других клиентов, которые готовы с нами болтать                            
            except ConnectionError:                                                 #если отключился
                print(f'клиент {adr} отключился')
                break
            if not data:
                break
            income_mes = data.decode('utf-8').strip()                               #расшифровываем полученное сообщение
            if not income_mes:                                                      #если вдруг пришли одни пробелы, то жестко игнорируем
                continue
            print(f'чат от {adr}: {income_mes}')
            await broadcast(f'{adr[1]}: {income_mes}', sender_writer=writer)        #рассылаем сообщение всем участникам
    finally:                                                                        
        chat_client.discard(writer)                                                 #удаляем отключившегося клиента. используем discard потому что он не выдает ошибку при удалении даже если уже нет объекта, который мы удаляем, как это делает remove
        await broadcast(f'сервер: {adr} покинул чат')                               #говорим всем остальным, что бро покинул чат

#общие функции для обоих режимов
async def handle_connection(reader, writer):                                        #объявляем корутину (асинхронная функция), запускается отдельно для каждого подключившегося клиента, reader и writer сами передаются библиотекой. здесь у нас создается один сокет, а reader и writer это просто красивые обертки для удобства, по факту мы работаем с одним объектом - сокетом
    adr = writer.get_extra_info("peername")                                         #узнаем сетевой адрес подключившегося клиента и записываем в котреж вида (ip, порт)
    try:
        mode_data = await reader.read(1024)                                         #ждем пока клиент не отправит свой режим работы. всегда первым придет именно режим
        if not mode_data:                                                           #если клиент подключился и сразу же отключился, ничего не оправив, закрываем сокет
            return
        mode = mode_data.decode('utf-8').strip()
        writer.write('ready'.encode('utf-8'))                                       #это нам очень важно, так как, во-первых, клиент ждет это сообщение перед отправкой собственных сообщений, во-вторых, сообщение с типом работы и с первым реальным сообщением с клиентом могло просто склеится в одну строчку
        await writer.drain()
        if mode == 'mode:ping':                                                     #если болтаем онлис сервером
            await handle_ping_mode(reader, writer, adr)
        elif mode == 'mode:chat':                                                   #если болтаем с другими клиентами через сервер
            await handle_chat_mode(reader, writer, adr)
    except ConnectionError:
        pass
    finally:
        try:
            writer.close()                                                          #делаем видимость закрытия сокет
            await writer.wait_closed()                                              #ждем, чтоб точно у нас этот сокет закрылся и освободились ресурсы, а только после всего этого идем дальше работать
        except OSError:                                                             #на винде вылезает ошибка, чтоб она не вылезала делаем вот это
            pass
        print("Disconnected by", adr)

async def main():                                                                   #настройка и работа всего сервера в целом
    #здесь появляется служебный сокет Listening Socket, он принимает новые подключения на порту
    server = await asyncio.start_server(handle_connection, "0.0.0.0", 0)            #запускаем TCP-сервер на всех интерфейсах и в свободном порту и привязываем к нему функцию handle_connection, теперь у нас для каждого клиента автоматически создается новая задача handle_connection
    actual_port = server.sockets[0].getsockname()[1]                                #узнаем какой порт выделила система
    conect = asyncio.create_task(conect_server_client(actual_port))                 #запускаем функцию в фоновом режиме
    try:
        async with server:                                                          #корректно освобаждаем порт и закрывааем все служебные сокеты
            await server.serve_forever()                                            #переводим сервер в фоновый режим ожидания, чтоб он работл пока мы его не убьем
    #здесь Listening Socket закрывается
    finally:
        conect.cancel()                                                             #останавливаем фоновую задачу при отключении сервера

if __name__ == "__main__":                                                          #программа запускается конкретно с этого файла
    try:
        asyncio.run(main())                                                         #создает главный цикл событий Event Loop, и не завершает программу, пока мы сами руками ее не остановим. Event Loop эта штука реализует многопользовательское соединение. вместо того, чтобы ждать пока мы поработаем с одним полностью, она запускает сразу несколько асинхронных задач в одном процессе или потоке
    except KeyboardInterrupt:
        print('сервер остановлен вручную')